// Builds js/test-bank.js for the final test (pages/test.html): every learning module's multiple-choice
// questions in English and Hindi, with the module titles, in course order. Run after editing any quiz:
//   node tools/build-test-bank.js
// Sources: js/mcq-*.js (the module quizzes) and the quiz inside js/lessons-market-rules.js.
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const js = path.join(__dirname, "..", "js");
const ctx = { console, Math, JSON, Object, Array, String, Number };
ctx.window = ctx;
vm.createContext(ctx);
const run = f => vm.runInContext(fs.readFileSync(path.join(js, f), "utf8"), ctx, { filename: f });
// The lesson catalogue gives titles and the course order; the module files add their questions to MCQ.
run("lesson-catalog.js");
["mcq-core.js", "mcq-1.js", "mcq-2.js", "mcq-3.js", "mcq-4.js", "mcq-5.js", "mcq-6.js", "mcq-7.js"].forEach(run);
// lessons-market-rules.js also edits lesson data the catalogue does not have; give it stand-ins.
vm.runInContext("var LESSON_OVERRIDES = { en: {}, hi: {} }; var MODULE_META = {}; var MODULE_CONTENT = { en: {}, hi: {} }; var MODULE_EXTRAS = { en: {}, hi: {} };", ctx);
try { run("lessons-market-rules.js"); } catch (e) { console.warn(`lessons-market-rules.js: ${e.message} (its quiz may be missing)`); }
vm.runInContext("this.__ = { LESSONS, MCQ, ORDER: LESSON_ORDER };", ctx);
const { LESSONS, MCQ, ORDER } = ctx.__;

const order = [...new Set(ORDER)].filter(s => LESSONS.en[s]);
const modules = [], missing = [];
const bank = { en: {}, hi: {} };
order.forEach(slug => {
 const en = MCQ.en[slug], hi = MCQ.hi[slug];
 if (!en || !en.length) { missing.push(slug); return; }
 modules.push({ slug, en: LESSONS.en[slug].title, hi: (LESSONS.hi[slug] || LESSONS.en[slug]).title, level: LESSONS.en[slug].level });
 bank.en[slug] = en;
 // Hindi questions must line up with the English ones (same questions in the same order). Their options may be in
 // a different order with their own correct index: a test attempt uses one language from start to finish.
 const valid = q => Array.isArray(q) && Array.isArray(q[1]) && q[1].length >= 2 && q[2] >= 0 && q[2] < q[1].length;
 bank.hi[slug] = hi && hi.length === en.length && hi.every(valid) ? hi : en;
 if (bank.hi[slug] === en) console.warn(`${slug}: Hindi questions do not match the English ones; English is used for both.`);
});
if (missing.length) console.warn(`Modules without questions (not in the test): ${missing.join(", ")}`);
const total = modules.reduce((s, m) => s + bank.en[m.slug].length, 0);
const dest = path.join(js, "test-bank.js");
fs.writeFileSync(dest, `// Generated by tools/build-test-bank.js — do not edit by hand. ${modules.length} modules, ${total} questions.\n// Each question: [question, [options], correct option index, explanation].\nwindow.MP_TEST_BANK = ${JSON.stringify({ modules, en: bank.en, hi: bank.hi })};\n`);
console.log(`Wrote ${total} questions from ${modules.length} modules (${(fs.statSync(dest).size / 1024).toFixed(0)} KB) to ${dest}`);
